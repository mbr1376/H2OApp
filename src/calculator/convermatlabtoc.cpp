 double Convermatlabtoc:: v1_pT(double P,double T)
{
     //kJ/(kg K)
    double Pi = P / 16.53;
    double tau = 1386 / T;
    double gamma_der_pi = 0;
    for (int i=0;i<34;i++) {
         gamma_der_pi = gamma_der_pi -( n1[i] * I1[i] * pow((7.1 - Pi),(I1[i] - 1)) * pow((tau - 1.222),J1[i]));
    }
    return  R * T / P * Pi * gamma_der_pi / 1000;

}

